#!/usr/bin/env bash
# generate-containerfile.sh — produces build/Containerfile from YAML manifests
# 
# Usage:
#   ./build/generate-containerfile.sh <device_id> <distro_id> <services...>
#
# This script:
# 1. Reads device/distro config from devices.yml
# 2. Resolves service dependencies
# 3. Generates a Containerfile with dnf install commands per service
# 4. Outputs to build/Containerfile

set -euo pipefail

REPO_ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$REPO_ROOT"

# Source libraries
source "$REPO_ROOT/shared/lib/yaml.sh"
source "$REPO_ROOT/shared/lib/service-loader.sh"

# Arguments
DEVICE_ID="${1:-}"
DISTRO_ID="${2:-}"
shift 2 || true
SERVICES=("$@")

if [[ -z "$DEVICE_ID" || -z "$DISTRO_ID" ]]; then
    echo "Usage: $0 <device_id> <distro_id> <services...>" >&2
    exit 1
fi

# Get base image URL from devices.yml
BASE_IMAGE_URL=$(yq -r ".devices[] | select(.id == \"$DEVICE_ID\") | .distros[] | select(.id == \"$DISTRO_ID\") | .base_image_url" "$REPO_ROOT/devices.yml")

if [[ -z "$BASE_IMAGE_URL" || "$BASE_IMAGE_URL" == "null" ]]; then
    echo "Error: base_image_url not found for $DEVICE_ID/$DISTRO_ID" >&2
    exit 1
fi

# Get device user and data_root from devices.yml
DEVICE_USER=$(yq -r ".devices[] | select(.id == \"$DEVICE_ID\") | .user" "$REPO_ROOT/devices.yml")
DATA_ROOT=$(yq -r ".devices[] | select(.id == \"$DEVICE_ID\") | .data_root // \"\"" "$REPO_ROOT/devices.yml")
[[ -z "$DATA_ROOT" || "$DATA_ROOT" == "null" ]] && DATA_ROOT="/home/$DEVICE_USER"

echo "Generating Containerfile for $DEVICE_ID/$DISTRO_ID"
echo "  Base image: $BASE_IMAGE_URL"
echo "  Device user: $DEVICE_USER"
echo "  Data root: $DATA_ROOT"
echo "  Services: ${SERVICES[*]}"

# Resolve service dependencies (topological order)
mapfile -t ORDERED_SERVICES < <(services_list_topo "$DEVICE_ID" "${SERVICES[@]}")
echo "  Build order: ${ORDERED_SERVICES[*]}"

# Get base packages from prepare service
PREPARE_PATH=$(resolve_service_path "$DEVICE_ID" "prepare")
BASE_PACKAGES=""
if [[ -f "$PREPARE_PATH/packages.yml" ]]; then
    BASE_PACKAGES=$(yq -r '.packages.fedora // [] | .[]' "$PREPARE_PATH/packages.yml" 2>/dev/null | tr '\n' ' ' | xargs)
fi
# Always include bootstrap packages for repo setup
BASE_PACKAGES="ca-certificates curl gnupg2 $BASE_PACKAGES"
BASE_PACKAGES=$(echo "$BASE_PACKAGES" | xargs)
echo "  Base packages: $BASE_PACKAGES"

OUTPUT="$REPO_ROOT/build/Containerfile"

# Generate the Containerfile directly using echo statements to avoid
# bash heredoc nesting issues with $ and {} expansion
{
    # Header
    cat << 'HEADER'
# Containerfile for AstralEmu ublue builds
# Generated by build/generate-containerfile.sh
# 
# Uses dnf (not rpm-ostree) because we build inside a Containerfile,
# where the filesystem is writable. rpm-ostree is only for deployed
# immutable systems.

HEADER

    # Base image
    echo "FROM $BASE_IMAGE_URL AS base-common"
    echo ""
    
    # Copy devices.yml and packages.yml files for repo setup
    echo "# Copy devices.yml for repo setup"
    echo "COPY setupfiles/devices.yml /etc/setupfiles/devices.yml"
    echo ""
    
    # Copy packages.yml files
    for svc in "${ORDERED_SERVICES[@]}"; do
        svc_path=$(resolve_service_path "$DEVICE_ID" "$svc")
        if [[ -f "$svc_path/packages.yml" ]]; then
            echo "COPY setupfiles/packages/${svc}.yml /etc/setupfiles/packages/${svc}.yml"
        fi
    done
    echo ""
    
    # Install yq
    echo "# Install yq for YAML parsing (not in Fedora repos)"
    echo 'RUN arch=$(uname -m) && curl -fsSL "https://github.com/mikefarah/yq/releases/latest/download/yq_linux_${arch}" -o /usr/local/bin/yq && chmod +x /usr/local/bin/yq'
    echo ""
    
    # Repository setup
    echo "# Setup repositories BEFORE any package installation"
    echo "RUN <<'REPOSETUP'"
    echo "set -e"
    echo "export DEVICE_ID=\"$DEVICE_ID\""
    echo "export DISTRO_ID=\"$DISTRO_ID\""
    echo ""
    echo "echo \"Configuring repositories for \$DEVICE_ID/\$DISTRO_ID...\""
    echo ""
    echo "if [ -f /etc/setupfiles/devices.yml ]; then"
    echo "    REPO_COUNT=\$(yq -r \".devices[] | select(.id == \\\"\$DEVICE_ID\\\") | .distros[] | select(.id == \\\"\$DISTRO_ID\\\") | .repos | length\" /etc/setupfiles/devices.yml 2>/dev/null || echo \"0\")"
    echo "    if [ \"\$REPO_COUNT\" -gt 0 ]; then"
    echo "        for i in \$(seq 0 \$((REPO_COUNT - 1))); do"
    echo "            REPO_NAME=\$(yq -r \".devices[] | select(.id == \\\"\$DEVICE_ID\\\") | .distros[] | select(.id == \\\"\$DISTRO_ID\\\") | .repos[\$i].name\" /etc/setupfiles/devices.yml)"
    echo "            REPO_URL=\$(yq -r \".devices[] | select(.id == \\\"\$DEVICE_ID\\\") | .distros[] | select(.id == \\\"\$DISTRO_ID\\\") | .repos[\$i].url\" /etc/setupfiles/devices.yml)"
    echo "            echo \"  Adding repo: \$REPO_NAME (\$REPO_URL)\""
    echo "            if [[ \"\$REPO_URL\" == *.repo ]]; then"
    echo "                curl -fsSL \"\$REPO_URL\" -o \"/etc/yum.repos.d/astralemu-\${REPO_NAME}.repo\""
    echo "            else"
    echo "                cat > \"/etc/yum.repos.d/astralemu-\${REPO_NAME}.repo\" << REPOEOF"
    echo "[astralemu-\${REPO_NAME}]"
    echo "name=AstralEmu - \${REPO_NAME}"
    echo "baseurl=\${REPO_URL}"
    echo "enabled=1"
    echo "gpgcheck=0"
    echo "REPOEOF"
    echo "            fi"
    echo "        done"
    echo "    fi"
    echo "fi"
    echo ""
    echo "dnf check-update || true"
    echo "echo \"Repositories configured successfully\""
    echo "REPOSETUP"
    echo ""
    
    # Install base packages
    echo "# Install base packages using dnf"
    echo "RUN dnf install -y $BASE_PACKAGES && dnf clean all"
    echo ""
    
    # Service stages
    echo "# ============================================================================="
    echo "# SERVICE STAGES"
    echo "# ============================================================================="
    echo ""
    
    FINAL_PARENT="base-common"
    
    for svc in "${ORDERED_SERVICES[@]}"; do
        svc_path=$(resolve_service_path "$DEVICE_ID" "$svc")
        
        if [[ -z "$svc_path" ]]; then
            echo "# Warning: Service '$svc' not found, skipping" >&2
            continue
        fi
        
        echo "FROM $FINAL_PARENT AS service-$svc"
        echo "# Service: $svc"
        
        # Get packages for this service
        svc_packages=""
        if [[ -f "$svc_path/packages.yml" ]]; then
            svc_packages=$(yq -r '.packages.fedora // [] | .[]' "$svc_path/packages.yml" 2>/dev/null | tr '\n' ' ' | xargs)
        fi
        
        if [[ -n "$svc_packages" ]]; then
            echo "RUN dnf install -y $svc_packages && dnf clean all"
        fi
        
        # Copy service files if they exist
        if [[ -d "$svc_path/files" ]]; then
            echo "COPY setupfiles/services/$svc/ /etc/astralemu/services/$svc/"
        fi
        
        # Run service install script if exists
        if [[ -f "$svc_path/install.sh" ]]; then
            echo "COPY setupfiles/services/$svc/install.sh /tmp/$svc-install.sh"
            echo "RUN chmod +x /tmp/$svc-install.sh && /tmp/$svc-install.sh && rm -f /tmp/$svc-install.sh"
        fi
        
        echo ""
        FINAL_PARENT="service-$svc"
    done
    
    # Final stage
    echo "# ============================================================================="
    echo "# FINAL STAGE"
    echo "# ============================================================================="
    echo "FROM $FINAL_PARENT AS final"
    echo ""
    
    # Copy setupfiles
    echo "# Copy first-boot scripts and service configs"
    echo "COPY setupfiles/ /etc/setupfiles/"
    echo ""
    
    # Post-install using echo to avoid heredoc nesting issues
    echo "# Post-install configuration for bootc"
    echo 'RUN <<'"'"'POSTINSTALL'"'"''
    echo "set -e"
    echo ""
    echo 'echo "=== Post-install configuration for bootc ==="'
    echo ""
    echo "# Timezone"
    echo "ln -sf /usr/share/zoneinfo/UTC /etc/localtime 2>/dev/null || true"
    echo ""
    echo "# Locale"
    echo 'echo "LANG=en_US.UTF-8" > /etc/locale.conf 2>/dev/null || true'
    echo ""
    echo "# Hostname"
    echo "echo \"$DEVICE_ID\" > /etc/hostname"
    echo "cat > /etc/hosts << HOSTSEOF"
    echo "127.0.0.1   localhost"
    echo "127.0.1.1   $DEVICE_ID"
    echo "::1         localhost ip6-localhost ip6-loopback"
    echo "HOSTSEOF"
    echo ""
    echo "# Copy systemd units and service scripts from setupfiles"
    echo "if [ -d /etc/setupfiles/services ]; then"
    echo '    find /etc/setupfiles/services -name "*.service" -exec cp {} /etc/systemd/system/ \; 2>/dev/null || true'
    echo '    find /etc/setupfiles/services -name "*.sh" -exec cp {} /usr/local/bin/ \; 2>/dev/null || true'
    echo '    find /etc/setupfiles/services -name "switch-dm*" -exec cp {} /usr/local/bin/ \; 2>/dev/null || true'
    echo "fi"
    echo 'chmod +x /usr/local/bin/*.sh 2>/dev/null || true'
    echo 'chmod +x /usr/local/bin/switch-dm* 2>/dev/null || true'
    echo ""
    echo "# Substitute device user placeholders in service files"
    echo 'find /etc/systemd/system -name "*.service" -exec sed -i \'
    echo "    -e \"s|REPLACE_DEVICE_USER|$DEVICE_USER|g\" \\"
    echo "    -e \"s|REPLACE_DEVICE_HOME|/home/$DEVICE_USER|g\" \\"
    echo "    -e \"s|REPLACE_DATA_ROOT|$DATA_ROOT|g\" \\"
    echo '    {} \; 2>/dev/null || true'
    echo 'find /usr/local/bin -type f -exec sed -i \'
    echo "    -e \"s|REPLACE_DEVICE_USER|$DEVICE_USER|g\" \\"
    echo "    -e \"s|REPLACE_DEVICE_HOME|/home/$DEVICE_USER|g\" \\"
    echo "    -e \"s|REPLACE_DATA_ROOT|$DATA_ROOT|g\" \\"
    echo '    {} \; 2>/dev/null || true'
    echo ""
    echo "# Create user"
    echo "if ! id -u $DEVICE_USER &>/dev/null; then"
    echo "    useradd -m -G video,audio,input,render -s /bin/bash $DEVICE_USER 2>/dev/null || true"
    echo "fi"
    echo ""
    echo "# Passwordless sudo"
    echo "echo \"$DEVICE_USER ALL=(ALL) NOPASSWD: ALL\" > /etc/sudoers.d/$DEVICE_USER 2>/dev/null || true"
    echo ""
    echo "# Enable systemd presets for bootc"
    echo "mkdir -p /usr/lib/systemd/system-preset"
    echo 'echo "enable NetworkManager.service" > /usr/lib/systemd/system-preset/40-astralemu.preset'
    echo 'echo "enable sshd.service" >> /usr/lib/systemd/system-preset/40-astralemu.preset'
    echo 'echo "enable bluetooth.service" >> /usr/lib/systemd/system-preset/40-astralemu.preset'
    echo 'echo "enable emulationstation.service" >> /usr/lib/systemd/system-preset/40-astralemu.preset'
    echo 'echo "enable services-first-boot.service" >> /usr/lib/systemd/system-preset/40-astralemu.preset'
    echo ""
    echo "# Set graphical target"
    echo "ln -sf /usr/lib/systemd/system/graphical.target /etc/systemd/system/default.target 2>/dev/null || true"
    echo ""
    echo "# Clean up"
    echo "rm -f /etc/setupfiles/devices.yml 2>/dev/null || true"
    echo ""
    echo 'echo "=== Post-install complete ==="'
    echo "POSTINSTALL"
    echo ""
    
    # Validate
    echo "# Validate bootc image"
    echo "RUN bootc container lint || true"
    echo ""
    
    # Labels
    echo "# Label the image"
    SERVICE_LIST=$(echo "${ORDERED_SERVICES[*]}" | tr ' ' ',')
    echo "LABEL org.astralemu.device=\"$DEVICE_ID\""
    echo "LABEL org.astralemu.distro=\"$DISTRO_ID\""
    echo "LABEL org.astralemu.services=\"$SERVICE_LIST\""
    echo "LABEL org.opencontainers.image.title=\"AstralEmu $DEVICE_ID\""
    echo "LABEL org.opencontainers.image.description=\"AstralEmu image for $DEVICE_ID ($DISTRO_ID)\""
    
} > "$OUTPUT"

echo "Generated: $OUTPUT"
echo "  Stages: base-common → ${ORDERED_SERVICES[*]} → final"